"""A SYNTHETIC demo property registry, to show the "coordinate -> registry parcels -> user picks one" flow.

Many countries publish a property registry (a rural environmental registry, a cadastre, an agricultural parcel
system). Pasto10 cannot ship yours, so this source answers from a small GeoJSON of invented parcels
(``domain/data/demo_registry.geojson``, generated by ``tools/make_demo_registry.py``) around the 13 non-control test
properties. The parcels are NOT real property boundaries: every candidate carries the warning ``synthetic_demo`` and the
source name ``DEMO registry``; the texts and images the user sees say so. To adapt the app, replace this class with a
reader of your country's registry (see ``national_registry_source.py`` and the README).
"""

import json
from pathlib import Path
from typing import Optional

from shapely.geometry import shape

from domain.schemas.candidate import GeometryOrigin, PropertyCandidate
from domain.schemas.feature import FeatureMetadata
from domain.services.property_sources import geometry_utils as geo

DATA_FILE = Path(__file__).resolve().parents[2] / "data" / "demo_registry.geojson"
SOURCE_NAME = "Pasto10 demo registry (synthetic)"
LICENSE = "Synthetic illustrative data, no real property boundaries (CC0)"
DEFAULT_SEARCH_RADIUS_M = 2000


class DemoRegistrySource:
    """Property source over the synthetic demo registry.

    Attributes:
        key (str): ``"demo_registry"``.
        data_file (Path): GeoJSON with the parcels.
    """

    key = "demo_registry"

    def __init__(self, data_file: Optional[Path] = None):
        """Creates the source (the file is read on first use).

        Args:
            data_file (Path, optional): GeoJSON FeatureCollection of parcels; defaults to the shipped sample.
        """
        self.data_file = data_file or DATA_FILE
        self._parcels: Optional[list] = None

    def _load(self) -> list:
        """Reads and caches the parcels as (shapely polygon, properties) pairs."""
        if self._parcels is None:
            data = json.loads(self.data_file.read_text(encoding="utf-8"))
            self._parcels = [(shape(item["geometry"]), item["properties"]) for item in data["features"]]
        return self._parcels

    def _candidate(self, polygon, properties: dict, distance_m: Optional[float]) -> PropertyCandidate:
        """Builds the candidate of a parcel with registry-style attributes (no owner data)."""
        registry_id = properties["registry_id"]
        return PropertyCandidate(
            candidate_id=registry_id, name=registry_id, origin=GeometryOrigin.REGISTERED_BOUNDARY, source=SOURCE_NAME,
            source_date="2026-01-01", geometry=geo.mapping(polygon), area_ha=round(float(properties["area_ha"]), 2),
            distance_m=None if distance_m is None else round(distance_m, 1),
            attributes=[
                FeatureMetadata(key="registry_id", value=registry_id),
                FeatureMetadata(key="registry_status", value=str(properties.get("status", "active"))),
                FeatureMetadata(key="registry_region", value=str(properties.get("region", ""))),
            ],
            license=LICENSE, warnings=["synthetic_demo"],
        )

    def find_by_point(self, latitude: float, longitude: float, search_radius_m: float = DEFAULT_SEARCH_RADIUS_M) -> list[PropertyCandidate]:
        """Returns the demo parcels within a radius of a coordinate, the one containing the point first.

        Args:
            latitude (float): Latitude in decimal degrees.
            longitude (float): Longitude in decimal degrees.
            search_radius_m (float): Search radius in meters.

        Returns:
            list[PropertyCandidate]: Candidates ordered by (contains the point, distance, area); empty when
            no parcel lies within the radius (for example around the negative-control points).
        """
        found = []
        for polygon, properties in self._load():
            distance = geo.distance_to_point_m(polygon, latitude, longitude)
            if distance <= search_radius_m:
                found.append(self._candidate(polygon, properties, distance))
        found.sort(key=lambda item: (item.distance_m != 0, item.distance_m or 0.0, item.area_ha))
        return found

    def find_by_id(self, identifier: str) -> Optional[PropertyCandidate]:
        """Returns the parcel with a registry id (case-insensitive, e.g. ``DEMO-BRA-0001``), or None.

        Args:
            identifier (str): Registry id.

        Returns:
            PropertyCandidate | None: The candidate (no distance), or None when the id is unknown.
        """
        wanted = identifier.strip().upper()
        for polygon, properties in self._load():
            if str(properties["registry_id"]).upper() == wanted:
                return self._candidate(polygon, properties, None)
        return None
